// Playwright CLI: the seeded product API, no session mutations.
async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const errors = []
  const onError = error => errors.push(error.message)
  page.on('pageerror', onError)
  const filters = () => page.getByRole('complementary', { name: 'Filters', exact: true })
  const overview = () => page.getByRole('complementary', { name: 'Traffic overview', exact: true })
  const toggle = () => page.getByRole('button', { name: 'Filters', exact: true })
  const sort = () => page.getByRole('combobox', { name: 'Sort traffic', exact: true })
  const open = async () => { if (await toggle().getAttribute('aria-expanded') !== 'true') await toggle().click() }
  const close = async () => { if (await toggle().getAttribute('aria-expanded') === 'true') await page.getByRole('button', { name: 'Close filters', exact: true }).click() }
  const waitTracks = count => page.waitForFunction(count => Number(document.querySelector('.atlas-composition')?.dataset.trackCount) === count, count)
  try {
    const { items } = await (await page.request.get('http://127.0.0.1:8091/api/infrareveal/sessions')).json()
    const recording = items.find(session => !session.active && session.name.startsWith('Example'))
    assert(recording, 'Seed the Example recording first')
    await page.goto(`http://127.0.0.1:5193/map/${recording.id}`)
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('slider', { name: 'Session timeline', exact: true }).waitFor()
    if (await page.getByRole('button', { name: 'Pause playback' }).count()) await page.getByRole('button', { name: 'Pause playback' }).click()
    await page.getByRole('slider', { name: 'Session timeline', exact: true }).press('Home')
    await page.getByRole('button', { name: 'Forward 10 seconds', exact: true }).click()
    await page.getByRole('button', { name: 'Forward 10 seconds', exact: true }).click()
    await waitTracks(3)
    if (await page.getByRole('button', { name: 'Pause playback' }).count()) await page.getByRole('button', { name: 'Pause playback' }).click()
    await open()
    assert(await filters().getByLabel('History', { exact: true }).inputValue() === '300000', 'Five-minute default changed')
    assert(await filters().getByRole('switch', { name: 'Only active now', exact: true }).getAttribute('aria-checked') === 'false', 'Active-only should default off')
    assert(await filters().getByRole('combobox', { name: 'Activity', exact: true }).count() === 0, 'Old activity modes remain')
    assert(await sort().evaluate(el => Boolean(el.closest('.atlas-header')) && el.parentElement.nextElementSibling?.id === 'traffic-filters-toggle'), 'Sort is not beside Filters')
    assert(await overview().getByRole('combobox').count() === 0, 'Sidebar still owns sorting')
    await filters().getByLabel('Search', { exact: true }).fill('SVT.SE')
    await waitTracks(1)
    const filteredTotal = await overview().locator('[data-direction-total="received"]').innerText()
    assert(await page.locator('.atlas-composition').getAttribute('data-destination-count') === '1', 'Map did not use the search filter')
    await overview().getByRole('button', { name: /^Tracks/ }).click()
    assert(await overview().locator('.atlas-track').count() === 1, 'Sidebar has a different search result')
    assert(await overview().locator('input[type="search"], [aria-label="Track filter"]').count() === 0, 'Sidebar still owns filters')
    await page.getByRole('button', { name: 'Browse activity blocks', exact: true }).click()
    await page.locator('.atlas-block-browser .atlas-block').first().waitFor()
    assert(await page.locator('.atlas-block-browser input[type="search"]').count() === 0, 'Activity blocks still own a search filter')
    assert((await page.locator('.atlas-block-browser .atlas-block strong').allTextContents()).every(label => label === 'svt.se'), 'Activity blocks ignored the shared search')
    await page.getByRole('button', { name: 'Close activity blocks', exact: true }).click()
    await open()
    await page.getByRole('button', { name: 'Expand traffic timeline', exact: true }).click()
    await page.locator('.atlas-detail-timeline[data-visible-lanes="1"]').waitFor()
    assert(await page.locator('.atlas-detail-track strong').innerText() === 'svt.se', 'Timeline search differs from sidebar')
    assert(await page.locator('[aria-label="Timeline lanes"], [aria-label="Timeline window"]').count() === 0, 'Local timeline filters remain')
    await page.locator('.atlas-detail-row').evaluateAll(rows => Promise.all(rows.flatMap(row => row.getAnimations().map(animation => animation.finished))))
    await page.screenshot({ path: 'output/playwright/shared-filters-timeline.png' })
    await filters().getByLabel('History', { exact: true }).selectOption('30000')
    await page.locator('.atlas-detail-timeline[data-bin-ms="100"]').waitFor()
    await filters().getByRole('switch', { name: 'Only active now', exact: true }).check()
    assert(await filters().getByText('Traffic within the last 15 seconds of the playhead.', { exact: true }).count() === 1, 'Active cutoff is unclear')
    await filters().getByRole('button', { name: 'Reset filters', exact: true }).click()
    await waitTracks(3)
    assert(await filters().getByRole('switch', { name: 'Only active now', exact: true }).getAttribute('aria-checked') === 'false', 'Reset left active-only enabled')
    for (const [order, expected] of [['volume', ['203.0.113.20', 'svt.se', 'news.example']], ['name', ['203.0.113.20', 'news.example', 'svt.se']]]) {
      await sort().selectOption(order)
      await page.waitForFunction(expected => {
        const names = selector => [...document.querySelectorAll(selector)].map(el => el.textContent)
        return JSON.stringify(names('.atlas-overview .atlas-track .atlas-destination-name')) === JSON.stringify(expected)
          && JSON.stringify(names('.atlas-detail-track strong')) === JSON.stringify(expected)
      }, expected)
    }
    await filters().getByLabel('Location', { exact: true }).selectOption('unlocated')
    await waitTracks(1)
    await page.locator('.atlas-detail-timeline[data-visible-lanes="1"]').waitFor()
    assert(await overview().locator('[data-direction-total="received"]').innerText() === '480.0 kB', 'Unlocated totals included other locations')
    for (const projection of ['equal-earth', 'mercator']) {
      await page.getByRole('button', { name: 'Open display settings' }).click()
      await page.getByLabel('Map projection', { exact: true }).selectOption(projection)
      await page.getByRole('button', { name: 'Close display settings' }).click()
      await page.locator(`.atlas-page[data-projection="${projection}"] .atlas-composition[data-track-count="1"]`).waitFor()
      assert(await page.locator('.atlas-composition').getAttribute('data-location-filter') === 'unlocated', 'Projection switch lost filters')
      assert(await sort().inputValue() === 'name', 'Projection switch lost shared ordering')
      await page.getByRole('button', { name: 'Back to map', exact: true }).click()
      assert(await page.locator('.atlas-composition').getAttribute('data-destination-count') === (projection === 'equal-earth' ? '1' : '0'), 'Projection included an excluded mapped destination')
      await page.getByRole('button', { name: 'Expand traffic timeline', exact: true }).click()
      await page.locator('.atlas-detail-timeline[data-visible-lanes="1"]').waitFor()
    }
    await open()
    await filters().getByRole('button', { name: 'Reset filters', exact: true }).click()
    await waitTracks(3)
    await filters().getByLabel('Search', { exact: true }).fill('not-a-real-service')
    await waitTracks(0)
    await page.locator('.atlas-detail-timeline[data-visible-lanes="0"]').waitFor()
    assert(await overview().locator('[data-direction-total="received"]').innerText() === '0 B', 'Empty search left unfiltered totals')
    await filters().getByRole('button', { name: 'Reset filters', exact: true }).click()
    await waitTracks(3)
    await filters().getByLabel('Search', { exact: true }).press('Escape')
    assert(await toggle().getAttribute('aria-expanded') === 'false', 'Escape did not close filters')
    assert(await page.locator('.atlas-detail-timeline').count() === 1, 'Escape also collapsed the timeline')
    assert(await toggle().evaluate(el => el === document.activeElement), 'Focus did not return to Filters')
    await page.getByRole('button', { name: 'Back to map', exact: true }).click()
    await overview().getByRole('button', { name: /^Locations/ }).click()
    await overview().locator('[data-location-id="18.0686,59.3293"]').click()
    await page.getByRole('button', { name: 'Close location details', exact: true }).waitFor()
    assert(await page.locator('.atlas-composition').getAttribute('data-location-filter') === '', 'Inspection silently changed global filters')
    assert(await page.locator('.atlas-location-inspector [data-location-track-id]').count() === 2, 'Location details included unrelated services')
    await page.getByRole('button', { name: 'Close location details', exact: true }).click()
    await open()
    await filters().getByLabel('Location', { exact: true }).selectOption('18.0686,59.3293')
    await waitTracks(2)
    await close()
    await overview().locator('[data-location-id="18.0686,59.3293"]').click()
    await page.getByRole('button', { name: 'Close location details', exact: true }).click()
    assert(await page.locator('.atlas-composition').getAttribute('data-location-filter') === '18.0686,59.3293', 'Closing details cleared global filters')
    await open()
    await filters().getByRole('button', { name: 'Reset filters', exact: true }).click()
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile filter drawer overflows')
    await page.screenshot({ path: 'output/playwright/shared-filters-mobile.png' })
    await close()
    await page.setViewportSize({ width: 320, height: 740 })
    await page.getByRole('button', { name: 'Expand traffic timeline', exact: true }).click()
    await sort().selectOption('volume')
    assert(await sort().isVisible(), 'Mobile sort is inaccessible')
    assert(await page.locator('.atlas-header').evaluate(el => el.scrollWidth <= el.clientWidth), 'Mobile header controls overflow')
    await page.getByRole('button', { name: 'Back to map', exact: true }).click()
    await page.locator('.atlas-filter-drawer').evaluate(el => Promise.all(el.getAnimations().map(animation => animation.finished)))
    assert(await page.locator('.atlas-map-container').evaluate(el => el.scrollLeft === 0 && Math.abs(el.querySelector('.atlas-filter-workspace').getBoundingClientRect().left - el.getBoundingClientRect().left) < 1), 'Filter drawer shifted the map sideways')
    assert(errors.length === 0, errors.join('; '))
    return { passed: true, filteredTotal, pageErrors: errors, checks: 'one search/activity/history/location state, matching lists/maps/lanes/totals, both projections, quiet/empty traffic, reset, independent details, keyboard closing and mobile layout' }
  } finally { page.off('pageerror', onError) }
}
