// Playwright CLI check against the seeded development API, without session mutations.
export default async (page, harness) => {
  const { map: base, recorded, live, assert, errors } = harness
  try {
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(`${base}/map/${recorded.id}`)
    await page.getByRole('button', { name: 'Open display settings' }).click()
    await page.locator('#map-projection').selectOption('equal-earth')
    await page.getByRole('button', { name: 'Dark', exact: true }).click()
    const fullscreen = page.getByRole('switch', { name: 'Fullscreen', exact: true })
    await fullscreen.click()
    await page.waitForFunction(() => document.fullscreenElement?.matches('.atlas-page'))
    await page.locator('[role="switch"][aria-labelledby="map-fullscreen-label"][aria-checked="true"]').waitFor()
    await page.waitForFunction(() => {
      const dialog = document.querySelector('.atlas-settings'), rect = dialog.getBoundingClientRect()
      return document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2)?.closest('dialog') === dialog
    })
    await page.screenshot({ path: 'output/playwright/fullscreen-settings.png' })
    await fullscreen.click()
    await page.waitForFunction(() => !document.fullscreenElement)
    await page.locator('[role="switch"][aria-labelledby="map-fullscreen-label"][aria-checked="false"]').waitFor()
    await fullscreen.click()
    await page.waitForFunction(() => Boolean(document.fullscreenElement))
    await page.evaluate(() => document.exitFullscreen())
    await page.locator('[role="switch"][aria-labelledby="map-fullscreen-label"][aria-checked="false"]').waitFor()
    await page.getByRole('button', { name: 'Close display settings' }).click()
    if (await page.getByRole('button', { name: 'Pause playback' }).count()) await page.getByRole('button', { name: 'Pause playback' }).click()
    await page.getByRole('button', { name: 'Forward 10 seconds', exact: true }).click()
    await page.getByRole('button', { name: 'Forward 10 seconds', exact: true }).click()
    assert(await page.locator('.atlas-timeline-labels > span').first().innerText() === new Date(recorded.started_ms).toISOString().slice(11, 19), 'Progress bar does not start at the session clock time')
    assert(await page.locator('.atlas-transport .atlas-time-readout, .atlas-transport [aria-label="Toggle fullscreen"]').count() === 0, 'Redundant time/fullscreen controls remain in the player')
    await page.getByRole('button', { name: 'Expand traffic timeline' }).click()
    await page.locator('.atlas-flow-envelope').first().waitFor()
    await page.getByRole('button', { name: 'Filters', exact: true }).click()
    assert(await page.getByRole('combobox', { name: 'History', exact: true }).inputValue() === '300000', 'Timeline should open on five minutes')
    await page.getByRole('button', { name: 'Close filters', exact: true }).click()
    await page.locator('.atlas-filter-drawer').evaluate(el => Promise.all(el.getAnimations().map(animation => animation.finished)))
    assert(Number(await page.locator('.atlas-detail-timeline').getAttribute('data-visible-lanes')) > 0, 'Recent capture must be visible immediately')
    assert(await page.locator('.atlas-detail-timeline > header, .atlas-timeline-toolbar, .atlas-timeline-options, .atlas-wave-quality').count() === 0, 'Redundant timeline header remains')
    assert(await page.locator('.atlas-detail-ruler').evaluate(el => Math.abs(el.getBoundingClientRect().top - el.closest('.atlas-detail-timeline').getBoundingClientRect().top)) < 1, 'Header space was not reclaimed')
    await page.screenshot({ path: 'output/playwright/traffic-timeline-dark.png' })
    const firstLane = page.locator('.atlas-detail-lane input').first()
    await firstLane.focus()
    await page.locator('.atlas-detail-timeline[data-held]').waitFor()
    await firstLane.press('ArrowLeft')
    await page.getByRole('button', { name: 'Play session', exact: true }).click()
    await page.locator('.atlas-detail-timeline:not([data-held])').waitFor()
    await page.getByRole('button', { name: 'Pause playback', exact: true }).click()
    await firstLane.focus()
    await page.locator('.atlas-detail-timeline[data-held]').waitFor()
    await page.getByRole('button', { name: 'Forward 10 seconds', exact: true }).click()
    await page.locator('.atlas-detail-timeline:not([data-held])').waitFor()
    await page.getByRole('button', { name: 'Filters', exact: true }).click()
    await page.getByRole('switch', { name: 'Only active now', exact: true }).check()
    await page.getByRole('switch', { name: 'Only active now', exact: true }).uncheck()
    await page.getByRole('button', { name: 'Close filters', exact: true }).click()
    await page.locator('.atlas-filter-drawer').evaluate(el => Promise.all(el.getAnimations().map(animation => animation.finished)))
    await page.getByRole('button', { name: 'Open display settings' }).click()
    assert(await page.locator('#map-quality').count() === 0, 'Rendering detail control still exists')
    await page.getByRole('button', { name: 'Light', exact: true }).click()
    await page.getByRole('button', { name: 'Close display settings' }).click()
    await page.screenshot({ path: 'output/playwright/traffic-timeline-light.png' })
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile layout overflows horizontally')
    await page.screenshot({ path: 'output/playwright/traffic-timeline-mobile.png' })
    await page.getByRole('button', { name: 'Back to map', exact: true }).click()
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('button', { name: 'Open display settings' }).click()
    await page.getByRole('button', { name: 'Dark', exact: true }).click()
    await page.locator('#map-projection').selectOption('mercator')
    await page.getByRole('button', { name: 'Close display settings' }).click()
    await page.locator('.atlas-map-surface[data-map-pitch]').waitFor()
    const shader = await page.evaluate(async () => (await import('/test-support/check-traffic-animation.js')).checkTrafficAnimation())
    assert(shader.passed, shader.failures.join('; '))
    await page.getByRole('button', { name: 'Expand traffic timeline' }).click()
    await page.locator('.atlas-flow-envelope').first().waitFor()
    await page.getByRole('button', { name: 'Back to map', exact: true }).click()
    await page.locator('.atlas-composition[data-workspace="map"]').waitFor()
    await page.goto(`${base}/map/${live.id}`)
    await page.getByRole('button', { name: 'Pause playback' }).click()
    await page.getByRole('button', { name: 'Expand traffic timeline' }).click()
    await page.getByRole('button', { name: /^(Go live|Live)$/ }).click()
    await page.locator('.atlas-page[data-playback-state="following"]').waitFor()
    assert(await page.getByRole('button', { name: 'Pause playback' }).count() === 1, 'Follow live must resume playback')
    assert(errors.length === 0, `Browser errors: ${errors.join('; ')}`)
    return { passed: true, pageErrors: errors, shaderChecks: shader.checks, checks: 'recorded traffic shapes, five-minute default, keyboard seeking, hold/resume, both projections, light/dark, mobile, removed detail settings, paused live → follow live' }
  } finally { await page.emulateMedia({ reducedMotion: 'no-preference' }) }
}
